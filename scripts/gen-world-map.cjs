// Run from a throwaway folder with dotted-map@2 installed (npm i dotted-map@2 --prefix <tmp>), not a project dependency:
//   node gen-world-map.cjs src/data/worldMap.ts src/assets/map/world-dots.svg
// Bakes a dotted world map into src/data/worldDots.ts (no runtime dependency).
const path = require('path');
const fs = require('fs');
const DottedMap = require('dotted-map').default;

const region = { lat: { min: -42, max: 70 }, lng: { min: -128, max: 152 } };
const map = new DottedMap({ width: 140, grid: 'diagonal', region });

const pins = {
  vizag: { lat: 17.69, lng: 83.22 },
  'United States': { lat: 38.5, lng: -97 },
  China: { lat: 31.2, lng: 117 },
  Japan: { lat: 35.7, lng: 139.5 },
  Vietnam: { lat: 14.5, lng: 107.8 },
  'European Union': { lat: 50.5, lng: 8 },
  'Middle East': { lat: 25, lng: 51.5 },
};
const pinXY = {};
for (const [k, p] of Object.entries(pins)) {
  const pin = map.getPin(p);
  pinXY[k] = [+pin.x.toFixed(2), +pin.y.toFixed(2)];
}
const pts = map.getPoints();
let w = 0, h = 0;
for (const p of pts) { w = Math.max(w, p.x); h = Math.max(h, p.y); }
const W = Math.ceil(w + 1), H = Math.ceil(h + 1);
pts.sort((a, b) => a.y - b.y || a.x - b.x);
let px = 0, py = 0;
const r = (n) => String(+n.toFixed(2)).replace(/^0\./, '.').replace(/^-0\./, '-.');
const d = pts.map((p) => { const s = `m${r(p.x - px)} ${r(p.y - py)}h0`; px = p.x; py = p.y; return s; }).join('');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}"><path d="${d.replace(/^m/, 'M')}" stroke="#fff" stroke-opacity=".28" stroke-width=".42" stroke-linecap="round"/></svg>`;
fs.writeFileSync(process.argv[3], svg);
const out = `// Generated by a one-off dotted-map script (2026-10-25); the dots are src/assets/map/world-dots.svg. Do not edit by hand.
// Region: lat ${region.lat.min}..${region.lat.max}, lng ${region.lng.min}..${region.lng.max}. Pins are map units in the same viewBox.
export const world = { w: ${W}, h: ${H} } as const;

export const pinXY: Record<string, readonly [number, number]> = ${JSON.stringify(pinXY)};
`;
const dest = process.argv[2];
fs.writeFileSync(dest, out);
console.log(pts.length, 'dots', w, h, pinXY, (svg.length / 1024).toFixed(1) + ' KB svg');
